package main

func main() {

	// one way of assigning variables
	var name string = "John Doe"
	var age int = 20
	var isMale bool = true
	var salary float64 = 10000.00

	println(name)
	println(age)
	println(isMale)
	println(salary)

	// another way of assigning variables
	name2 := "John Doe"
	age2 := 20
	isMale2 := true
	salary2 := 10000.00

	println(name2)
	println(age2)
	println(isMale2)
	println(salary2)
}
